-- Fixed UUID scheme for seed data
-- Pattern: 00000000-0000-0000-XXYY-ZZZZZZZZZZZ0
-- XX = entity type, YY = sequence, ZZ = padding

-- Entity Types (XX)
-- 01 = Branches
-- 02 = Roles
-- 03 = FD Plans
-- 04 = Application Users
-- 05 = Agents
-- 06 = Customers
-- 07 = Savings Plans
-- 08 = Transaction Channels
-- 09 = Accounts
-- 10 = Fixed Deposits
-- 11 = Transactions
-- 12 = Interest Runs

