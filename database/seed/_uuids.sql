-- Fixed UUID scheme for seed data
-- Pattern: 00000000-0000-0000-XXYY-ZZZZZZZZZZZ0
-- XX = entity type, YY = sequence, ZZ = padding

-- Entity Types (XX)
-- 01 = Branches
-- 02 = Roles
-- 03 = FD Plans
-- 04 = Application Users (and their dependent Agent profiles)
-- 05 = Customers
-- 06 = Savings Plans
-- 07 = Transaction Channels
-- 08 = Accounts
-- 09 = Fixed Deposits
-- 10 = Transactions
-- 11 = Interest Runs

